# The dovetail alone let go: pulled up, its flanks pry the TPU groove open. The side lips are undercut at 45° too
# (so they print), but with the rigid part outside: what they pry on is PETG, and their wide spacing resists
# twisting the cradle off.
# The rail and lips run under the camera pocket, so the camera is raised until the cavity floor clears both by WALL.
